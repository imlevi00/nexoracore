-- ---------------------------------------------------------------------------
-- فراوانکردنی کۆڵۆمی is_enabled لە package_feature_permissions
-- ---------------------------------------------------------------------------
-- کێشە: کۆڵۆمی `is_enabled` جۆری `tinyint(1)` بوو (سایند، تەنها تا 127).
--       ئەم کۆڵۆمە هەم بەهای بولی (0/1) بۆ feature ئاساییەکان هەڵدەگرێت و
--       هەم سنووری ژمارەیی وەک `videos_max_count` (تا 1000) و
--       `employees_max_count`. هەر نرخێکی سنوور > 127:
--         - لە MySQLـی strict: UPDATE شکست دەهێنێت و نرخە کۆنە نزمەکە دەمێنێتەوە
--           (بۆیە ئەدمین وا دەزانێت سنوورەکەی بەرزکردووە بەڵام نەکراوە).
--         - لە non-strict: بۆ 127 کورت دەکرێتەوە.
--       ئەنجام: بەکارهێنەر پێش گەیشتن بە سنووری ڕاستەقینە ڕێگری لێدەکرێت.
--
-- چارەسەر: کۆڵۆمەکە بکە `INT` تاکو بتوانێت هەموو سنوورەکانی کاتالۆگ (تا 1000+)
--          بەبێ کورتکردنەوە یان شکست هەڵبگرێت. بەهای 0/1 بۆ feature بولییەکان
--          هەروەها بەبێ کێشە کاردەکات.
--
-- تێبینی: پاش جێبەجێکردنی ئەم migrationـە، پێویستە ئەدمین سنووری ڤیدیۆکان لە
--          پەڕەی «دەسەڵاتە وردەکان»ی پاکێجەکە دووبارە پاشەکەوت بکات، چونکە لەوانەیە
--          نرخی پێشوو نزم مابێتەوە یان بۆ 127 کورت کرابێتەوە.
-- ---------------------------------------------------------------------------

ALTER TABLE `package_feature_permissions`
    MODIFY `is_enabled` INT NOT NULL DEFAULT 1;
